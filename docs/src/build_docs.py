FILE_TO_KEY = {f: k for k, _, f, _ in TABS}
FILE_TO_LABEL = {f: label for _, label, f, _ in TABS}
ROOT_CLASSES = ("js", "flow-paused")   # classes the shell sets on <html>


# ---------- HTML ----------

def split_page(src):
    styles = re.findall(r"<style[^>]*>(.*?)</style>", src, re.S)
    m = re.search(r"<body[^>]*>(.*)</body>", src, re.S)
    body = m.group(1) if m else src
    body = re.sub(r"<script\b.*?</script>", "", body, flags=re.S)
    css = "\n".join(re.sub(r"/\* fonts:begin \*/.*?/\* fonts:end \*/", "", s, flags=re.S) for s in styles)
    return css, body


def doc_link(name, frag):
    key = FILE_TO_KEY.get(name)
    if key is None:
        return None
    return f"#{key}-{frag}" if frag else f"#tab-{key}"


def rewrite_body(key, body):
    ids = set(re.findall(r'\bid="([^"]+)"', body))
    p = key + "-"
    body = re.sub(r'\bid="([^"]+)"', lambda m: f'id="{p}{m.group(1)}"', body)
    body = re.sub(r'\bfor="([^"]+)"', lambda m: f'for="{p}{m.group(1)}"' if m.group(1) in ids else m.group(0), body)

    def idlist(m):
        return f'{m.group(1)}="' + " ".join(p + t if t in ids else t for t in m.group(2).split()) + '"'
    body = re.sub(r'\b(aria-labelledby|aria-describedby|aria-controls)="([^"]*)"', idlist, body)
    body = re.sub(r'\b((?:xlink:)?href)="#([^"]+)"',
                  lambda m: f'{m.group(1)}="#{p}{m.group(2)}"' if m.group(2) in ids else m.group(0), body)
    body = re.sub(r"url\(#([^)]+)\)", lambda m: f"url(#{p}{m.group(1)})" if m.group(1) in ids else m.group(0), body)

    def page_href(m):
        target = doc_link(m.group(2), m.group(3))
        return f'href="{target}"' if target else m.group(0)
    body = re.sub(r'href="(?:\.\./)?(docs/)?([a-z0-9-]+\.html)(?:#([^"]*))?"', page_href, body)

    def code_ref(m):
        target = doc_link(m.group(1), m.group(2))
        if not target:
            return m.group(0)
        return f'<a href="{target}">{FILE_TO_LABEL[m.group(1)]} tab' + (f" &sect;&nbsp;{m.group(2)}" if m.group(2) else "") + "</a>"
    body = re.sub(r"(?<!>)<code>docs/([a-z0-9-]+\.html)(?:#([a-z0-9-]+))?</code>", code_ref, body)
    return body


# ---------- CSS scoping ----------

def split_selectors(sel):
    out, depth, cur = [], 0, ""
    for ch in sel:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return [s.strip() for s in out if s.strip()]


def scope_selector(sel, P):
    m = re.match(r"^(?::root|html|body)(?![\w-])(.*)$", sel, re.S)
    if m:
        rest = m.group(1)
        # "html body x" or "html x": drop the html/body part, keep the rest under the tab
        rest = re.sub(r"^\s+body(?![\w-])", "", rest)
        return P + rest
    for cls in ROOT_CLASSES:
        m = re.match(r"^\." + re.escape(cls) + r"(?![\w-])(.*)$", sel, re.S)
        if m:
            rest = m.group(1).strip()
            return f".{cls} {P} {rest}" if rest else f".{cls} {P}"
    return f"{P} {sel}"


def parse_blocks(css):
    """Yield (prelude, body or None) for top-level statements; body is the text inside braces."""
    i, n = 0, len(css)
    while i < n:
        j = i
        while j < n and css[j] not in "{;":
            j += 1
        if j >= n:
            break
        prelude = css[i:j].strip()
        if css[j] == ";":
            yield prelude, None
            i = j + 1
            continue
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        yield prelude, css[j + 1:k - 1]
        i = k


def scope_css(css, P, hoisted):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    out = []
    for prelude, body in parse_blocks(css):
        if body is None:
            if prelude:
                hoisted.append(prelude + ";")
            continue
        low = prelude.lower()
        if low.startswith(("@media", "@supports", "@container")):
            out.append(prelude + "{" + scope_css(body, P, hoisted) + "}")
        elif low.startswith(("@font-face", "@keyframes", "@-webkit-keyframes", "@page")):
            hoisted.append(prelude + "{" + body + "}")
        elif low.startswith("@"):
            hoisted.append(prelude + "{" + body + "}")
        else:
            sels = ",".join(scope_selector(s, P) for s in split_selectors(prelude))
            out.append(sels + "{" + body.strip() + "}")
    return "\n".join(out)


