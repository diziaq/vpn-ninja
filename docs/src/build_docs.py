def build():
    fonts = open(os.path.join(HERE, "fonts.css"), encoding="utf-8").read()
    hoisted, scoped, sections, tabbar = [], [], [], []
    for key, label, fname, purpose in TABS:
        if key == "plan":
            src = gen_guide.build()
        else:
            src = open(os.path.join(HERE, "pages", fname), encoding="utf-8").read()
        css, body = split_page(src)
        P = f"#tab-{key}"
        scoped.append(f"/* ---- tab {key}: {fname} ---- */\n" + scope_css(css, P, hoisted))
        body = rewrite_body(key, body)
        title = htmlmod.escape(label)
        sections.append(f'<section class="tab-panel" id="tab-{key}" role="tabpanel" aria-label="{title}" '
                        f'data-title="{title}" data-source="docs/src/{"gen_guide.py" if key == "plan" else "pages/" + fname}">'
                        f"{body}</section>")
        tabbar.append(f'<li role="presentation"><a href="#tab-{key}" role="tab" aria-controls="tab-{key}" '
                      f'title="{htmlmod.escape(purpose)}">{title}</a></li>')
    seen, hoist_unique = set(), []
    for h in hoisted:
        if h not in seen:
            seen.add(h)
            hoist_unique.append(h)
    page = f"""<!doctype html>
<html lang="en" data-doc="vpn-ninja-docs">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>vpn-ninja handbook</title>
<script>document.documentElement.classList.add('js');</script>
<style>
/* Generated by docs/src/build_docs.py; edit the sources in docs/src/, then rebuild. */
{fonts}
{SHELL_CSS}
{chr(10).join(hoist_unique)}
{chr(10).join(scoped)}
</style>
</head>
<body>
<header class="shell"><div class="shell-in">
  <p class="brand">vpn-ninja</p>
  <nav aria-label="Documents"><ul class="tabs" role="tablist">{"".join(tabbar)}</ul></nav>
</div></header>
<p class="nojs-note">All documents follow one after another below; the tab links jump to each.</p>
{'<hr class="tab-sep">'.join(sections)}
<script>{SHELL_JS}</script>
</body>
</html>
"""
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(page)
    ids = re.findall(r'\bid="([^"]+)"', page)
    dup = sorted({i for i in ids if ids.count(i) > 1})
    hrefs = set(re.findall(r'href="#([^"]+)"', page)) | set(re.findall(r"url\(#([^)]+)\)", page))
    dangling = sorted(h for h in hrefs if h not in set(ids))
    print(f"wrote {OUT}: {len(TABS)} tabs, {len(page)} bytes")
    if dup:
        print("DUPLICATE ids:", dup)
    if dangling:
        print("DANGLING links:", dangling)
    return 1 if (dup or dangling) else 0


if __name__ == "__main__":
    sys.exit(build())
