#!/usr/bin/env python3
"""Build docs/index.html: every HTML document of the project in one offline file, one tab each.

Sources (edit these, never docs/index.html):
  docs/src/gen_guide.py + docs/LESSONS.md   the Plan tab (the path as cards), generated
  docs/src/pages/<name>.html                one complete page per tab, written by hand
  docs/src/fonts.css                        IBM Plex faces (SIL OFL 1.1), embedded once

Run:  python3 docs/src/build_docs.py

Each page keeps its own look: its CSS is scoped to its tab, its element ids get the tab's prefix
(`setup-flash`, `arrival-counter`), and links between pages become tab links. Link to another
page's section from any source as `router-setup.html#flash` (or `docs/router-setup.html#flash`);
`<code>docs/router-setup.html#flash</code>` in text becomes a link named after the tab. Without JavaScript all tabs are
shown one after another; with it, one tab at a time and the address (#setup-flash) opens the
right tab, so the browser's Back button returns to the plan.
"""
